// The row and input types the plain-TypeScript rules depend on, with no client and no `import.meta`. The files in this
// folder re-export them, so web code is unchanged; the iPhone app (mobile/) imports the rules and reaches the types
// here, because its type checker must not follow an import into src/db/client.ts.
import type { Insert, Row } from './types.ts';

export type DailyLog = Row<'daily_logs'>;
export type DailyLogInsert = Insert<'daily_logs'>;

/** The columns the supplement before/after comparison reads, so it does not pull whole rows. */
export type EffectLog = Pick<DailyLog, 'log_date' | 'weight' | 'mood' | 'total_cals' | 'protein' | 'water_ml' | 'active_kcal' | 'habits'>;

export type Habit = Row<'habits'>;
/** What a person fills in. The id, owner, creation time and order are set by the database or by the caller. */
export type HabitInput = Pick<Insert<'habits'>, 'name' | 'kind' | 'unit' | 'goal' | 'better'>;

export type Medication = Row<'medications'>;
/** The columns a person fills in. `active` is generated by the database from end_date, so it is never written. */
export type MedicationInput = Omit<Insert<'medications'>, 'id' | 'created_at' | 'active'>;

export type Biomarker = Row<'biomarkers'>;
export type BiomarkerReading = Row<'biomarker_readings'>;

export interface BloodworkData {
  biomarkers: Biomarker[];
  readings: BiomarkerReading[];
}

/** What a person types in. The id, owner and creation time are set by the database. */
export type ReadingInput = Required<Pick<Insert<'biomarker_readings'>, 'biomarker_id' | 'measured_at' | 'value' | 'source'>> &
  Pick<Insert<'biomarker_readings'>, 'notes' | 'ref_low' | 'ref_high'>;

export type Profile = Row<'profile'>;

/** What the "Your details" card saves: the facts the age, the ranges and the calorie suggestion are worked out from. */
export interface DetailsValues {
  sex: 'male' | 'female';
  date_of_birth: string;
  /** worked out from the date on the day of saving; the app recomputes it from the date every time it reads it */
  age: number;
  height_cm: number;
  activity_level: string;
}

/** What the Goals screen saves into the profile row. The weights and dates are required, the daily targets are not. */
export interface GoalValues {
  start_weight: number;
  goal_weight: number;
  start_date: string;
  goal_date: string;
  calorie_target: number | null;
  protein_target: number | null;
}
