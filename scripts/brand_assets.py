#!/usr/bin/env python3
"""
Writes the production brand assets for the chosen logo (option B, the section cut) from the geometry in
scripts/brand_logos.py, so the app, the favicon and the link preview all share one mark:

    pip install fonttools
    python3 scripts/brand_assets.py

  src/components/brand-mark.ts   the mark as path data, imported by src/components/brand.tsx
  public/favicon.svg             the mark in paper on a red tile, which reads on light and dark browser tabs
  docs/brand/og-image.html       the source of the link preview image (1200 by 630)

The pictures made from those, public/og.png, public/favicon.ico and public/apple-touch-icon.png, come from
scripts/brand_rasters.mjs.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

from brand_logos import PAPER, RED, mark_b, n  # noqa: E402

FAVICON_SCALE = 0.23     # artwork units to tile units: the 200 unit mark becomes 46 of the tile's 64, tuned so it holds at 16 px


def write(path, text):
    full = os.path.join(ROOT, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, 'w') as f:
        f.write(text)
    print('wrote', path, f'({len(text) // 1024 or 1} KB)')


def main():
    m = mark_b()
    x0, y0, x1, y1 = m['bbox']
    viewbox = f'{n(x0)} {n(y0)} {n(x1 - x0)} {n(y1 - y0)}'

    write('src/components/brand-mark.ts',
          '// Generated by scripts/brand_assets.py from the geometry in scripts/brand_logos.py. Do not edit by hand.\n'
          '// The Intus mark: a slash, solid at its head and dissolving into halftone dots. One path, so it takes any fill.\n'
          f"export const MARK_VIEWBOX = '{viewbox}';\n"
          f"export const MARK_PATH = '{m['d']}';\n")

    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    write('public/favicon.svg',
          '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">'
          f'<rect width="64" height="64" rx="14" fill="{RED}"/>'
          f'<g transform="translate(32 32) scale({FAVICON_SCALE}) translate({n(-cx)} {n(-cy)})">'
          f'<path fill="{PAPER}" d="{m["d"]}"/></g></svg>\n')

    write('docs/brand/og-image.html', og_html(m['d'], viewbox))


